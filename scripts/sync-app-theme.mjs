import fs from "node:fs/promises";
import path from "node:path";

const DEFAULT_APP_THEME_PATH =
  "/Users/colinfreed/Projects/AdventureWare/Products/Kwipoo/app/kwipoo-teal-theme.css";

const OUTPUT_PATH = path.resolve(
  "src/lib/styles/kwipoo-brand-theme.generated.css",
);

const SHARED_PREFIXES = [
  "--text-scaling",
  "--base-",
  "--heading-",
  "--anchor-",
  "--anchor-text-decoration",
  "--spacing",
  "--radius-",
  "--default-border-width",
  "--default-divide-width",
  "--default-ring-width",
  "--color-primary-",
  "--color-secondary-",
  "--color-tertiary-",
  "--color-success-",
  "--color-warning-",
  "--color-error-",
];

function resolveThemePath() {
  return process.env.KWIPOO_APP_THEME_FILE || DEFAULT_APP_THEME_PATH;
}

function shouldKeepVariable(name) {
  return SHARED_PREFIXES.some((prefix) => name.startsWith(prefix));
}

function parseThemeVariables(cssText) {
  const blockMatch = cssText.match(
    /\[data-theme="[^"]+"\]\s*\{([\s\S]*?)\}\s*$/,
  );

  if (!blockMatch) {
    throw new Error(
      'Could not find a [data-theme="..."] CSS block in the app theme file.',
    );
  }

  const body = blockMatch[1];
  const variables = [];

  for (const match of body.matchAll(
    /^\s*(--[A-Za-z0-9-_]+)\s*:\s*([^;]+);/gm,
  )) {
    const [, name, value] = match;
    if (shouldKeepVariable(name)) {
      variables.push([name, value.trim()]);
    }
  }

  if (variables.length === 0) {
    throw new Error(
      "No shared brand variables were extracted from the app theme file.",
    );
  }

  return variables;
}

function buildOutput(themePath, variables) {
  const lines = [
    "/* Generated by scripts/sync-app-theme.mjs. Do not edit manually. */",
    `/* Source: ${themePath} */`,
    "@theme {",
    ...variables.map(([name, value]) => `  ${name}: ${value};`),
    "}",
    "",
  ];

  return lines.join("\n");
}

async function main() {
  const themePath = resolveThemePath();
  const checkOnly = process.argv.includes("--check");

  const cssText = await fs.readFile(themePath, "utf8");
  const variables = parseThemeVariables(cssText);
  const nextOutput = buildOutput(themePath, variables);

  if (checkOnly) {
    const currentOutput = await fs.readFile(OUTPUT_PATH, "utf8");
    if (currentOutput !== nextOutput) {
      throw new Error(
        [
          "The generated website brand theme is out of sync with the app theme.",
          `Run: KWIPOO_APP_THEME_FILE="${themePath}" npm run theme:sync`,
        ].join("\n"),
      );
    }
    console.log("Theme is in sync.");
    return;
  }

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, nextOutput, "utf8");
  console.log(`Updated ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
