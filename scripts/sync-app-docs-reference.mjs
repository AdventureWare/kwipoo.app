import fs from "node:fs/promises";
import path from "node:path";
import prettier from "prettier";

const DEFAULT_APP_DOCS_REFERENCE_PATH =
  "/Users/colinfreed/Projects/AdventureWare/Products/Kwipoo/app/docs/derived/website/docs-reference.json";

const OUTPUT_PATH = path.resolve(
  "src/lib/content/docs/entity-reference.generated.ts",
);

function resolveAppDocsReferencePath() {
  const explicitFile = process.env.KWIPOO_APP_DOCS_REFERENCE_FILE;

  if (explicitFile) {
    return explicitFile;
  }

  const explicitRepo = process.env.KWIPOO_APP_REPO_PATH;

  if (explicitRepo) {
    return path.join(
      explicitRepo,
      "docs",
      "derived",
      "website",
      "docs-reference.json",
    );
  }

  return DEFAULT_APP_DOCS_REFERENCE_PATH;
}

function validateDocsReference(candidate) {
  if (!candidate || typeof candidate !== "object" || Array.isArray(candidate)) {
    throw new Error("Website docs reference must be an object.");
  }

  const entities = candidate.entities;

  if (!Array.isArray(entities)) {
    throw new Error("Website docs reference must include an entities array.");
  }

  for (const entity of entities) {
    if (!entity || typeof entity !== "object" || Array.isArray(entity)) {
      throw new Error("Website docs entity references must be objects.");
    }

    for (const field of [
      "slug",
      "label",
      "summary",
      "routePath",
      "schemaExport",
      "schemaFile",
      "formFile",
    ]) {
      if (
        typeof entity[field] !== "string" ||
        entity[field].trim().length === 0
      ) {
        throw new Error(`Docs entity reference is missing "${field}".`);
      }
    }

    if (!Array.isArray(entity.routeFiles) || !Array.isArray(entity.fields)) {
      throw new Error(
        `Docs entity reference ${entity.slug} must include routeFiles and fields arrays.`,
      );
    }

    for (const field of entity.fields) {
      if (!field || typeof field !== "object" || Array.isArray(field)) {
        throw new Error(
          `Docs entity reference ${entity.slug} must include field objects.`,
        );
      }

      for (const key of ["key", "label", "status", "description", "example"]) {
        if (typeof field[key] !== "string" || field[key].trim().length === 0) {
          throw new Error(
            `Docs entity reference ${entity.slug} has a field missing "${key}".`,
          );
        }
      }
    }
  }

  return entities;
}

async function buildOutput(sourcePath, entities) {
  return prettier.format(
    [
      "// This file is generated by `npm run docs:sync`. Do not edit by hand.",
      `// Source: ${sourcePath}`,
      'import type { DocsEntityReference } from "./entity-reference";',
      "",
      `export const generatedDocsEntityReferences: DocsEntityReference[] = ${JSON.stringify(entities, null, 2)};`,
      "",
    ].join("\n"),
    {
      parser: "typescript",
    },
  );
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const ifAvailable = process.argv.includes("--if-available");
  const sourcePath = resolveAppDocsReferencePath();

  let sourceText;

  try {
    sourceText = await fs.readFile(sourcePath, "utf8");
  } catch (error) {
    if (
      ifAvailable &&
      error &&
      typeof error === "object" &&
      "code" in error &&
      error.code === "ENOENT"
    ) {
      console.log(
        `Kwipoo app docs reference not found at ${sourcePath}. Keeping existing website docs snapshot.`,
      );
      return;
    }

    throw error;
  }

  const entities = validateDocsReference(JSON.parse(sourceText));
  const nextOutput = await buildOutput(sourcePath, entities);

  if (checkOnly) {
    const currentOutput = await fs.readFile(OUTPUT_PATH, "utf8");

    if (currentOutput !== nextOutput) {
      throw new Error(
        [
          "The generated website docs reference snapshot is out of sync with the app docs reference.",
          `Run: KWIPOO_APP_DOCS_REFERENCE_FILE="${sourcePath}" npm run docs:sync`,
        ].join("\n"),
      );
    }

    console.log("Website docs reference snapshot is in sync.");
    return;
  }

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, nextOutput, "utf8");
  console.log(`Updated ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
